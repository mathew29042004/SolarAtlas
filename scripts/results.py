"""Generate docs/RESULTS.md from the published snapshot and run logs: every number is measured.

    python scripts/results.py [--region tamil_nadu] > docs/RESULTS.md
"""
from __future__ import annotations

import argparse
import json
import platform
import sys
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from solaratlas import config  # noqa: E402


def q(con, sql, params=()):
    cur = con.cursor().execute(sql, params)
    cols = [d[0] for d in cur.description]
    return [dict(zip(cols, r, strict=True)) for r in cur.fetchall()]


def n(v, d=0):
    return "–" if v is None else f"{v:,.{d}f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--region", default="tamil_nadu")
    a = ap.parse_args()
    db = config.SERVING / "current" / "solaratlas.duckdb"
    con = duckdb.connect(str(db), read_only=True)
    r = a.region
    s = q(con, "SELECT * FROM region_summary WHERE region = ?", [r])[0]
    meta = q(con, "SELECT run_id, published_at FROM _meta")[0]
    # logs/runs.jsonl, not the snapshot: a snapshot cannot contain the run that published it
    log = ROOT / "logs" / "runs.jsonl"
    runs = [json.loads(line) for line in log.read_text().splitlines()] if log.exists() else []
    runs = [x for x in runs if x["region"] == r and x["status"] == "success"]
    full = next((x for x in reversed(runs) if "bronze" in json.loads(x["timings"])), None)
    mem = json.loads(full["stats"]).get("driver_mem") if full else None
    incr = [x for x in runs if '"mode": "incremental"' in (x["stats"] or "")]
    land = ROOT / "data" / "landing" / "buildings" / f"release={s['release']}" / f"region={r}" / "_summary.json"
    lsum = json.loads(land.read_text()) if land.exists() else {}
    dq = q(con, 'SELECT "check", passed, observed FROM dq_results WHERE region = ? AND run_id = '
                "(SELECT max(run_id) FROM dq_results WHERE region = ?)", [r, r])
    model = json.loads(q(con, "SELECT metrics FROM model_metrics WHERE region = ? ORDER BY trained_at DESC "
                              "LIMIT 1", [r])[0]["metrics"])
    types = q(con, """SELECT building_type, count(*) AS n, sum(roof_kwp)/1000 AS mwp, sum(viable::int) AS v,
                             median(payback_years) AS pb, sum(type_source = 'osm')::int AS tagged
                      FROM building_solar WHERE region = ? GROUP BY 1 ORDER BY mwp DESC""", [r])
    dist = q(con, "SELECT * FROM district_summary WHERE region = ? ORDER BY potential_gwh_year DESC LIMIT 10", [r])
    scen = q(con, """SELECT scenario, any_value(label) AS label, sum(viable_homes) AS homes,
                            sum(subsidy_cr) AS subsidy, sum(viable_mwp) AS mwp FROM scenario_district
                     WHERE region = ? GROUP BY 1""", [r])
    base = next(x for x in scen if x["scenario"] == "baseline")
    order = list(config.load("scenarios")["scenarios"])
    scen.sort(key=lambda x: order.index(x["scenario"]))

    out = []
    w = out.append
    w("# Measured results\n")
    w(f"Generated by `scripts/results.py` from serving snapshot `{meta['run_id']}` "
      f"(published {str(meta['published_at'])[:19]}). Machine: {platform.machine()} Mac, 16 GB RAM, "
      f"Spark `local[4]`{f', {mem} driver for the full run' if mem else ''}. "
      f"Nothing here is estimated by hand.\n")
    w("## Scale\n")
    w("| | |\n|---|---|")
    if lsum:
        w(f"| Buildings downloaded (65 tiles, Overture {s['release']}) | {n(lsum['rows'])} ({lsum['bytes'] / 1e9:.2f} GB) |")
    w(f"| Inside Tamil Nadu after clipping to the state polygon | **{n(s['buildings'])}** |")
    w(f"| Quarantined by quality rules | {n(s['quarantined'])} |")
    w(f"| Districts / wards & towns | {n(s['districts'])} / "
      f"{n(q(con, 'SELECT count(*) AS c FROM locality_summary WHERE region = ?', [r])[0]['c'])} |")
    w(f"| Places (POIs) used as classifier features | "
      f"{n(json.loads(full['stats']).get('places')) if full else '–'} |")
    if full:
        t = json.loads(full["timings"])
        w(f"| Full pipeline from empty tables, bronze → publish | **{n(sum(t.values()) / 60, 1)} min** "
          f"({', '.join(f'{k} {n(v)} s' for k, v in t.items())}) |")
    if incr:
        x = incr[-1]
        st = json.loads(x["stats"])
        w(f"| Incremental run (only changed buildings recomputed in gold) | "
          f"{n(st['gold_buildings']['changed'])} changed, gold {n(json.loads(x['timings']).get('gold'))} s |")
    w("")
    w("## Quality gate (latest run)\n")
    w("| Check | Result | Observed |\n|---|---|---|")
    for d in dq:
        w(f"| {d['check']} | {'PASS' if d['passed'] else 'FAIL'} | {d['observed']} |")
    w("\n## Rooftop potential, Tamil Nadu\n")
    w("| | |\n|---|---|")
    w(f"| Roof area | {n(s['roof_km2'])} km² |")
    w(f"| Technical potential (every eligible roof) | {n(s['potential_mwp'] / 1000, 1)} GW → "
      f"{n(s['potential_gwh_year'] / 1000, 1)} TWh/yr |")
    w(f"| Roofs that pay back within 7 years | **{n(s['viable_buildings'])}** ({n(s['viable_mwp'] / 1000, 1)} GW) |")
    w(f"| ...of which homes | {n(s['viable_homes'])} of {n(s['homes'])} |")
    w(f"| Investment for all viable roofs | ₹{n(s['viable_investment_cr'])} crore |")
    w(f"| PM Surya Ghar subsidy they would draw | ₹{n(s['viable_subsidy_cr'])} crore |")
    w(f"| Yearly bill savings | ₹{n(s['viable_saving_cr_year'])} crore |")
    w(f"| CO₂ avoided at full technical potential | {n(s['co2_kt_per_year'] / 1000, 1)} Mt/yr |")
    w(f"| Mean yield | {n(s['mean_yield_kwh_kwp'])} kWh/kWp/yr |")
    w("\nTechnical potential is an upper bound, not an adoption forecast.\n")
    w("## By building type\n")
    w("| Type | Buildings | OSM-tagged | Potential | Viable roofs | Median payback |\n|---|---|---|---|---|---|")
    for t in types:
        w(f"| {t['building_type']} | {n(t['n'])} | {n(t['tagged'])} | {n(t['mwp'])} MW | {n(t['v'])} | "
          f"{n(t['pb'], 1)} yrs |")
    w("\n## Top 10 districts\n")
    w("| # | District | Buildings | Potential | Viable | Investment | Median payback |\n|---|---|---|---|---|---|---|")
    for i, d in enumerate(dist, 1):
        w(f"| {i} | {d['district']} | {n(d['buildings'])} | {n(d['potential_mwp'])} MW | {n(d['viable_mwp'])} MW | "
          f"₹{n(d['viable_investment_cr'])} cr | {n(d['median_payback_years'], 1)} yrs |")
    w("\n## Policy scenarios (whole state, viable = payback ≤ 7 years)\n")
    w("| Scenario | Viable homes | Change | Subsidy outlay | Extra subsidy per extra home |\n|---|---|---|---|---|")
    for x in scen:
        extra = x["homes"] - base["homes"]
        per = (x["subsidy"] - base["subsidy"]) * 1e7 / extra if extra > 0 else None
        w(f"| {x['label']} | {n(x['homes'])} | {'+' if extra > 0 else ''}{n(extra)} | ₹{n(x['subsidy'])} cr | "
          f"{'₹' + n(per) if per else '–'} |")
    w("\n## Building-type classifier (Spark ML random forest)\n")
    w(f"Trained on {n(sum(model['labels'].values()))} OSM-tagged buildings; held-out test set of "
      f"{n(model['test_rows'])}. **Accuracy {model['accuracy']:.1%}, macro-F1 {model['macro_f1']:.2f}.**\n")
    w("| Class | Labels | Precision | Recall | F1 |\n|---|---|---|---|---|")
    for k, v in model["per_class"].items():
        w(f"| {k} | {n(model['labels'][k])} | {v['precision']} | {v['recall']} | {v['f1']} |")
    dep = model.get("deployed")
    if dep:
        w(f"\n**Deployed rule** (non-residential only at ≥ {dep['threshold']:.0%} confidence, since class "
          f"weighting otherwise over-predicts rare types across 25M buildings), same held-out set: "
          f"accuracy {dep['accuracy']:.1%}.\n")
        w("| Class | Precision | Recall |\n|---|---|---|")
        for k, v in dep["per_class"].items():
            w(f"| {k} | {v['precision']} | {v['recall']} |")
    w(f"\nTop features: {', '.join(f[0] for f in model['top_features'][:6])}.\n")
    w("## Assumptions that move these numbers\n")
    w("Unverified tariffs (TN domestic slabs, commercial ₹8.80, industrial ₹8.00), ₹60k/kW home capex, "
      "consumption estimated from footprint, crowding-based shading, net metering within each bill. "
      "All live in `config/` and every number above is regenerated from them.")
    print("\n".join(out))


if __name__ == "__main__":
    main()
