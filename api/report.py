"""One printable HTML page per building: what fits on the roof, what it makes, what it pays back."""
from __future__ import annotations

import html


def _inr(v) -> str:
    return "–" if v is None else f"₹{v:,.0f}"


def _row(k, v) -> str:
    return f"<tr><td>{html.escape(k)}</td><td>{v}</td></tr>"


def render(b: dict) -> str:
    e = lambda v: html.escape(str(v if v is not None else ""))  # noqa: E731
    if b.get("household"):
        h, units = b["household"]["recommended"], b["household"]["units_bimonthly"]
        econ = (f"<h2>For your home (about {units} units per 2-month bill)</h2><table>"
                + _row("Recommended system", f"{h['kwp']} kWp")
                + _row("Cost before subsidy", _inr(h["capex_inr"]))
                + _row("PM Surya Ghar subsidy", _inr(h["subsidy_inr"]))
                + _row("Your cost", _inr(h["net_cost_inr"]))
                + _row("Bill now → with solar", f"{_inr(h['bill_before_inr'])} → {_inr(h['bill_after_inr'])}")
                + _row("Yearly saving", _inr(h["annual_saving_inr"]))
                + _row("Payback", f"{h['payback_years']} years" if h["payback_years"] else "never")
                + _row("25-year net saving", _inr(h["lifetime_saving_inr"])) + "</table>"
                + ("<p class='note'>Consumption is estimated from the roof size. Change it with "
                   "<code>?units=</code> in the address bar.</p>"))
    elif b.get("business"):
        h = b["business"]
        econ = (f"<h2>For this {e(b['building_type'])} building</h2><table>"
                + _row("System", f"{h['kwp']} kWp")
                + _row("Generation", f"{h['annual_kwh']:,} kWh/yr")
                + _row("Investment (no subsidy)", _inr(h["capex_inr"]))
                + _row("Yearly saving", _inr(h["annual_saving_inr"]))
                + _row("Payback", f"{h['payback_years']} years" if h["payback_years"] else "never")
                + "</table>")
    else:
        econ = "<p>This roof is too small for a rooftop system.</p>"
    if b.get("type_source") == "osm":
        src = "from OpenStreetMap"
    elif b.get("building_type") == "residential":
        src = "estimated by model"
    else:
        src = f"estimated by model, {round((b.get('type_prob') or 0) * 100)}% confidence"
    roof = ("<table>"
            + _row("Footprint", f"{b['footprint_m2']:,.0f} m²")
            + _row("Usable for panels", f"{b['usable_roof_m2']:,.0f} m²")
            + _row("Maximum system", f"{b['roof_kwp']:,.1f} kWp")
            + _row("Building type", f"{e(b['building_type'])} ({e(src)})")
            + _row("Sunshine here", f"{b['annual_yield_kwh_kwp']:,.0f} kWh per kWp per year")
            + _row("Shade from neighbours (estimate)", f"{(b.get('shading_loss') or 0) * 100:.0f}%")
            + _row("Full-roof generation", f"{b['annual_kwh']:,.0f} kWh/yr")
            + _row("CO₂ avoided", f"{b['co2_t_per_year']:,.1f} t/yr") + "</table>")
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1"><title>Solar report</title>
<style>
body{{font:15px/1.5 system-ui,sans-serif;max-width:720px;margin:24px auto;padding:0 16px;color:#1d1f23;background:#fff}}
h1{{font-size:22px;margin:0}} h2{{font-size:16px;margin:24px 0 6px}} .sub{{color:#626872}}
table{{border-collapse:collapse;width:100%}} td{{padding:6px 0;border-bottom:1px solid #e3e1da}}
td:last-child{{text-align:right;font-weight:600}} .note{{font-size:12px;color:#626872}}
button{{margin:8px 0;padding:6px 12px}} @media print{{button{{display:none}}}}
</style></head><body>
<h1>Rooftop solar report</h1>
<p class="sub">{e(b.get('locality'))}{', ' if b.get('locality') else ''}{e(b.get('district'))} ·
{b['lat']:.5f}, {b['lon']:.5f} · building {e(b['id'][:8])}</p>
<button onclick="print()">Print / save as PDF</button>
<h2>Your roof</h2>{roof}
{econ}
<p class="note" style="margin-top:24px">Screening estimate from satellite footprints (Overture Maps, ODbL)
and NASA POWER climate data. No site survey: roof condition, tilt and exact shading are not checked.
Tariff rates are not yet verified against the TNERC order. Generated by SolarAtlas India.</p>
</body></html>"""
